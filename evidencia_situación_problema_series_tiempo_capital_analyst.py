# Main analysis loop
for interval in intervals:
    print(f"\n=== Analysis for {interval} Interval ===")
    data = {}
    for stock in stocks:
        series = load_data(stock, interval)
        if series is None:
            continue
        data[stock] = series

    # Align series by common timestamps
    if len(data) == 3:
        print("\nAligning series by common timestamps:")
        for stock in stocks:
            print(f"{stock} series length: {len(data[stock])}")
        # Combine series into a DataFrame and keep only common timestamps
        aligned_data = pd.concat([data['PG'], data['MSFT'], data['CAT']], axis=1, keys=stocks)
        aligned_data = aligned_data.dropna()  # Keep only rows with data for all stocks
        print(f"Aligned data length: {len(aligned_data)}")
        data['PG'] = aligned_data['PG']
        data['MSFT'] = aligned_data['MSFT']
        data['CAT'] = aligned_data['CAT']

    for stock in stocks:
        if stock in data:
            series = data[stock]
            random_walk_test(series, stock, interval)
            adf_test(series, stock, interval)
            kpss_test(series, stock, interval)
            fit_ar(series, stock, interval)
            fit_arma(series, stock, interval)
            fit_arima(series, stock, interval)

    if len(data) == 3:
        cointegration_test(data['PG'], data['MSFT'], data['CAT'], stocks, interval)

