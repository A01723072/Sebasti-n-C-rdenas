# Function to get sheet names from an Excel file
def get_sheet_names(file_path):
    try:
        workbook = openpyxl.load_workbook(file_path)
        return workbook.sheetnames
    except Exception as e:
        print(f"Error reading sheet names from {file_path}: {e}")
        return []

# Function to load data
def load_data(stock, interval):
    file_path = data_dir / f'{stock}_{interval}.xlsx'
    if not file_path.exists():
        print(f"File {file_path} not found.")
        return None

    # Get all sheet names
    sheet_names = get_sheet_names(file_path)
    print(f"\nSheet names in {file_path}: {sheet_names}")
    if not sheet_names:
        print(f"No sheets found in {file_path}.")
        return None

    # Try the default sheet name first
    try:
        df = pd.read_excel(file_path, engine='openpyxl', sheet_name=default_sheet_name, header=0, parse_dates=[date_column])
        df = df.set_index(date_column)  # Set 'Local Date' as the index
        print(f"\nLoaded {file_path} (Sheet: {default_sheet_name}):")
        print(f"Columns: {list(df.columns)}")
        print(f"First few rows:\n{df.head()}")
        if close_column not in df.columns:
            print(f"'{close_column}' column not found in {default_sheet_name}.")
            return try_other_sheets(file_path, sheet_names)
        return df[close_column].dropna()
    except ValueError as e:
        print(f"Error reading {default_sheet_name} from {file_path}: {e}")
        return try_other_sheets(file_path, sheet_names)
    except Exception as e:
        print(f"Unexpected error reading {file_path}: {e}")
        return None

# Function to try other sheets if default sheet fails
def try_other_sheets(file_path, sheet_names):
    for sheet in sheet_names:
        try:
            df = pd.read_excel(file_path, engine='openpyxl', sheet_name=sheet, header=0, parse_dates=[date_column])
            df = df.set_index(date_column)  # Set 'Local Date' as the index
            print(f"\nTrying sheet {sheet} in {file_path}:")
            print(f"Columns: {list(df.columns)}")
            print(f"First few rows:\n{df.head()}")
            if close_column in df.columns:
                print(f"Found '{close_column}' in sheet {sheet}.")
                return df[close_column].dropna()
            else:
                print(f"'{close_column}' column not found in sheet {sheet}.")
        except Exception as e:
            print(f"Error reading sheet {sheet} from {file_path}: {e}")
    print(f"No sheet in {file_path} contains '{close_column}' column.")
    return None

# Random walk test (variance ratio test approximation)
def random_walk_test(series, name, interval):
    print(f"\nRandom Walk Test for {name} ({interval}):")
    returns = series.pct_change().dropna()
    var_1 = returns.var()
    aggregated = series.resample('4T' if '5minutes' in interval else '4H').last().pct_change().dropna()
    var_agg = aggregated.var()
    ratio = var_agg / (4 * var_1)
    print(f"Variance Ratio: {ratio:.4f}")
    print("Ratio ≈ 1 suggests random walk behavior.")

    # Plot original and aggregated series
    plt.figure(figsize=(10, 6))
    plt.plot(series, label='Original Series', alpha=0.7)
    plt.plot(aggregated.index, aggregated * series.mean(), label='Aggregated Series (scaled)', linestyle='--')  # Scale for visibility
    plt.title(f'{name} ({interval}) - Random Walk Test')
    plt.xlabel('Date')
    plt.ylabel('Price')
    plt.legend()
    plt.tight_layout()
    plot_data.append((f'{name} ({interval}) - Random Walk Test', save_plot_to_base64_and_show()))

# ADF test for stationarity
def adf_test(series, name, interval):
    print(f"\nADF Test for {name} ({interval}):")
    result = adfuller(series, autolag='AIC')
    print(f'ADF Statistic: {result[0]:.4f}')
    print(f'p-value: {result[1]:.4f}')
    print(f'Critical Values: {result[4]}')
    if result[1] < 0.05:
        print("Series is likely stationary (reject null of unit root).")
    else:
        print("Series is likely non-stationary (fail to reject unit root).")

    # Plot series and differences
    plt.figure(figsize=(10, 6))
    plt.subplot(2, 1, 1)
    plt.plot(series, label='Original Series')
    plt.title(f'{name} ({interval}) - ADF Test: Original Series')
    plt.xlabel('Date')
    plt.ylabel('Price')
    plt.legend()

    plt.subplot(2, 1, 2)
    diff_series = series.diff().dropna()
    plt.plot(diff_series, label='First Difference', color='orange')
    plt.title('First Difference')
    plt.xlabel('Date')
    plt.ylabel('Price Difference')
    plt.legend()
    plt.tight_layout()
    plot_data.append((f'{name} ({interval}) - ADF Test', save_plot_to_base64_and_show()))

# KPSS test for stationarity
def kpss_test(series, name, interval):
    print(f"\nKPSS Test for {name} ({interval}):")
    statistic, p_value, lags, crit = kpss(series, regression='c', nlags='auto')
    print(f'KPSS Statistic: {statistic:.4f}')
    print(f'p-value: {p_value:.4f}')
    print(f'Critical Values: {crit}')
    if p_value < 0.05:
        print("Series is likely non-stationary (reject null of stationarity).")
    else:
        print("Series is likely stationary (fail to reject stationarity).")

    # Plot series and differences
    plt.figure(figsize=(10, 6))
    plt.subplot(2, 1, 1)
    plt.plot(series, label='Original Series')
    plt.title(f'{name} ({interval}) - KPSS Test: Original Series')
    plt.xlabel('Date')
    plt.ylabel('Price')
    plt.legend()

    plt.subplot(2, 1, 2)
    diff_series = series.diff().dropna()
    plt.plot(diff_series, label='First Difference', color='orange')
    plt.title('First Difference')
