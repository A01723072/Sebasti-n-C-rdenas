# Cointegration test
def cointegration_test(series1, series2, series3, names, interval):
    print(f"\nCointegration Test ({interval}):")
    pairs = [(0, 1), (0, 2), (1, 2)]
    for i, j in pairs:
        s1 = series1
        s2 = series2 if i == 0 and j == 1 else series3
        name1, name2 = names[i], names[j]
        score, p_value, _ = coint(s1, s2, trend='c')
        print(f"{name1} vs {name2}: p-value = {p_value:.4f}")
        if p_value < 0.05:
            print(f"Evidence of cointegration between {name1} and {name2}.")
        else:
            print(f"No evidence of cointegration between {name1} and {name2}.")

        # Plot series and spread
        plt.figure(figsize=(10, 6))
        plt.subplot(2, 1, 1)
        plt.plot(s1, label=name1)
        plt.plot(s2, label=name2)
        plt.title(f'{name1} vs {name2} ({interval}) - Cointegration Test')
        plt.xlabel('Date')
        plt.ylabel('Price')
        plt.legend()

        plt.subplot(2, 1, 2)
        spread = s1 - s2  # Simple difference as a proxy for spread
        plt.plot(spread, label='Spread', color='purple')
        plt.title('Spread (Difference)')
        plt.xlabel('Date')
        plt.ylabel('Price Difference')
        plt.legend()
        plt.tight_layout()
        plot_data.append((f'{name1} vs {name2} ({interval}) - Cointegration Test', save_plot_to_base64_and_show()))

# AR model fitting
def fit_ar(series, name, interval):
    print(f"\nAR Model Fitting for {name} ({interval}):")
    result = adfuller(series)
    data = series
    if result[1] >= 0.05:
        print("Series is non-stationary; applying differencing for AR model.")
        data = series.diff().dropna()

    best_aic = float("inf")
    best_lag = None
    best_model = None

    for lag in range(1, 4):
        try:
            model = AutoReg(data, lags=lag)
            results = model.fit()
            aic = results.aic
            if aic < best_aic:
                best_aic = aic
                best_lag = lag
                best_model = results
        except:
            continue

    if best_model is None:
        print("No suitable AR model found.")
        return

    print(f"Best AR({best_lag}) model: AIC = {best_aic:.2f}")
    print(best_model.summary())

    # Plot diagnostics
    fig, axes = plt.subplots(2, 2, figsize=(12, 8))
    axes[0, 0].plot(best_model.resid)
    axes[0, 0].set_title('Residuals')
    plot_acf(best_model.resid, ax=axes[0, 1])
    plot_pacf(best_model.resid, ax=axes[1, 0])
    axes[1, 1].hist(best_model.resid, bins=30)
    axes[1, 1].set_title('Residual Histogram')
    plt.tight_layout()
    plot_data.append((f'{name} ({interval}) - AR({best_lag}) Diagnostics', save_plot_to_base64_and_show()))

    # Plot fitted values
    plt.figure(figsize=(10, 6))
    plt.plot(data, label='Actual')
    plt.plot(best_model.fittedvalues, label='Fitted', linestyle='--')
    plt.title(f'{name} ({interval}) - AR({best_lag}) Fit')
    plt.xlabel('Date')
    plt.ylabel('Price')
    plt.legend()
    plt.tight_layout()
    plot_data.append((f'{name} ({interval}) - AR({best_lag}) Fit', save_plot_to_base64_and_show()))

