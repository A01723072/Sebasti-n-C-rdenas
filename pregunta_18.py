# 4. Fitting ARIMA model (p,d,q) = (1,1,1)
model = ARIMA(money, order=(1,1,1)).fit()
print('\nARIMA(1,1,1) Model Summary:')
print(model.summary())

# Forecasting 12 steps ahead
forecast_steps = 12
forecast = model.forecast(steps=forecast_steps)
forecast_index = np.arange(len(money), len(money) + forecast_steps)

# Plotting ARIMA Fit and Forecast
arima_fitted = model.fittedvalues
plt.figure(figsize=(12,6))
plt.plot(time, money, label='Historical M1 Money Supply')
plt.plot(time, arima_fitted, label='ARIMA(1,1,1) Fitted', color='purple')
plt.plot(forecast_index, forecast, label='Forecast', color='red')
plt.title('ARIMA(1,1,1) Model Fit and Forecast')
