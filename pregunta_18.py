import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from statsmodels.tsa.arima.model import ARIMA
from statsmodels.tsa.stattools import adfuller, kpss
import warnings
import base64
import io

warnings.filterwarnings("ignore")

# Reading the Excel file (assumes file is uploaded to Colab)
df = pd.read_excel("21.1_Q18.xlsx")

# Extracting the time and money columns
time = df['TIME']
money = np.array(df['MONEY'])

# Function to convert plot to base64-encoded string
def plot_to_base64():
    buffer = io.BytesIO()
    plt.savefig(buffer, format='png')
    buffer.seek(0)
    img_str = base64.b64encode(buffer.getvalue()).decode('utf-8')
    buffer.close()
    return img_str

# Function to perform ADF test for stationarity
def adf_test(series, title=''):
    result = adfuller(series, autolag='AIC')
    print(f'ADF Test on {title}')
    print(f'ADF Statistic: {result[0]}')
    print(f'p-value: {result[1]}')
    print('Critical Values:')
    for key, value in result[4].items():
        print(f'\t{key}: {value}')
    if result[1] <= 0.05:
        print("Strong evidence against null hypothesis, series is stationary.")
    else:
        print("Weak evidence against null hypothesis, series is non-stationary.")

# Function to perform KPSS test for stationarity
def kpss_test(series, title=''):
    result = kpss(series, regression='c', nlags='auto')
    print(f'\nKPSS Test on {title}')
    print(f'KPSS Statistic: {result[0]}')
    print(f'p-value: {result[1]}')
    print('Critical Values:')
    for key, value in result[3].items():
        print(f'\t{key}: {value}')
    if result[1] <= 0.05:
        print("Strong evidence against null hypothesis, series is non-stationary.")
    else:
        print("Weak evidence against null hypothesis, series is stationary.")

# Testing stationarity on original series
adf_test(money, 'M1 Money Supply')
kpss_test(money, 'M1 Money Supply')

# Differencing the series to achieve stationarity
money_diff = np.diff(money)
adf_test(money_diff, 'Differenced M1 Money Supply')
kpss_test(money_diff, 'Differenced M1 Money Supply')

# List to store base64-encoded images
img_base64_list = []

# 1. Random Walk Check (ARIMA(0,1,0))
random_walk_model = ARIMA(money, order=(0,1,0)).fit()
print('\nRandom Walk Model Summary:')
print(random_walk_model.summary())

# Plotting Random Walk
rw_fitted = random_walk_model.fittedvalues
plt.figure(figsize=(12,6))
plt.plot(time, money, label='Historical M1 Money Supply')
plt.plot(time, rw_fitted, label='Random Walk Fitted', color='green')
plt.title('Random Walk Model (ARIMA(0,1,0)) Fit')
plt.xlabel('Time (Months from Jan 1951)')
plt.ylabel('M1 Money Supply (Billions $)')
plt.legend()
plt.grid(True)
img_base64_list.append(plot_to_base64())
